//! Golden-fixture generator for the on-chain registry set commitment
//! (`src/l1/contracts/src/RegistrySetCommitment.sol`): 5 deterministic
//! 32-byte SPHINCS+ public keys, their SHA3-256 leaves, the height-3 root
//! and per-slot membership paths — byte-identical to the circuit-side
//! registry semantics (`../registry.rs`, asserted against the same `sha3`
//! crate). Paste the printed values into RegistrySetCommitmentTest.t.sol.

use sha3::digest::{ExtendableOutput, Update as XofUpdate, XofReader};
use sha3::{Digest, Sha3_256, Shake256};

const LEAVES: usize = 8;
const HEIGHT: usize = 3;
const N_PKS: usize = 5;

fn sha3_256(data: &[u8]) -> [u8; 32] {
    let mut h = Sha3_256::new();
    Digest::update(&mut h, data);
    h.finalize().into()
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn main() {
    // Deterministic 32-byte public keys (stand-ins for PK.seed || PK.root).
    let pks: Vec<[u8; 32]> = (0..N_PKS)
        .map(|i| {
            let mut h = Shake256::default();
            XofUpdate::update(&mut h, b"qs-m4-fixture-pk");
            XofUpdate::update(&mut h, &(i as u32).to_be_bytes());
            let mut o = [0u8; 32];
            h.finalize_xof().read(&mut o);
            o
        })
        .collect();

    let mut levels: Vec<Vec<[u8; 32]>> = vec![vec![[0u8; 32]; LEAVES]];
    for (i, pk) in pks.iter().enumerate() {
        levels[0][i] = sha3_256(pk);
    }
    for _ in 0..HEIGHT {
        let prev = levels.last().unwrap();
        let mut next = Vec::with_capacity(prev.len() / 2);
        for pair in prev.chunks(2) {
            let mut d = [0u8; 64];
            d[..32].copy_from_slice(&pair[0]);
            d[32..].copy_from_slice(&pair[1]);
            next.push(sha3_256(&d));
        }
        levels.push(next);
    }

    println!("// generated by threshold-m3/src/bin/fixture.rs");
    for (i, pk) in pks.iter().enumerate() {
        println!("pk[{i}]   = hex\"{}\"", hex(pk));
    }
    for (i, l) in levels[0].iter().take(N_PKS).enumerate() {
        println!("leaf[{i}] = 0x{}", hex(l));
    }
    println!("root    = 0x{}", hex(&levels[HEIGHT][0]));
    for i in 0..N_PKS {
        let path: Vec<String> = (0..HEIGHT)
            .map(|j| format!("0x{}", hex(&levels[j][(i >> j) ^ 1])))
            .collect();
        println!("path[{i}] = [{}]", path.join(", "));
    }
}
